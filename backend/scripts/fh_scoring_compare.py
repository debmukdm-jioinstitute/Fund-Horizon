"""Side-by-side of FH scoring modes A and B on the live screener frame. Writes docs/FH_SCORING_COMPARISON.md.

Usage: .venv/bin/python scripts/fh_scoring_compare.py
(The earlier absolute-threshold scoring was removed; data/fh_scoring_baseline_legacy.json keeps its last scores for reference.)
"""
import copy, sys, warnings
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
import pandas as pd  # noqa: E402
from app.backoffice import fh_recommended, fh_score, mf_screener  # noqa: E402

base_cfg = fh_score.load_config()
scored = mf_screener._scored({}, None)
raw = scored[[c for c in scored.columns if not c.startswith(("fh_", "fhd_", "fhc_"))]]
ref = pd.to_datetime(raw["nav_date"], format="%d-%b-%Y", errors="coerce").max()
frames = {}
for mode in ("A", "B"):
    cfg = copy.deepcopy(base_cfg)
    cfg["ratios"]["mode"] = mode
    frames[mode] = fh_score.score_frame(raw.copy(), cfg=cfg, ref=ref)
A, B = frames["A"], frames["B"]

out = ["# FH scoring: mode A vs mode B", "", "Generated by `backend/scripts/fh_scoring_compare.py`.", "", "| Metric | A | B |", "|---|---|---|"]
for k, f in (("Funds scored", lambda x: int(x["fh_score"].notna().sum())), ("Average score", lambda x: round(x["fh_score"].mean(), 1)),
             ("Buy", lambda x: int((x["fh_signal"] == "Buy").sum())), ("Hold", lambda x: int((x["fh_signal"] == "Hold").sum())),
             ("Sell", lambda x: int((x["fh_signal"] == "Sell").sum())), ("Needs review", lambda x: int((x["fh_signal"] == "Needs review").sum())),
             ("Meet the auto-list bar", lambda x: int(x["fh_auto"].sum()))):
    out.append(f"| {k} | {f(A)} | {f(B)} |")
d = (B["fh_score"] - A["fh_score"]).dropna()
out += ["", f"B differs from A by at most {d.max():.1f} points (mean {d.mean():.2f}); signal differs for {(A['fh_signal'] != B['fh_signal']).sum()} funds.", "",
        "## Curated FH list", "| Fund | A | B | Data status |", "|---|---|---|---|"]
for c in fh_recommended.FH_RECOMMENDED_MF_CODES:
    i = A.index[A["code"] == c]
    if len(i):
        i = i[0]
        out.append(f"| {A['name'][i][:48]} | {A['fh_score'][i]} {A['fh_signal'][i]} | {B['fh_score'][i]} {B['fh_signal'][i]} | {A['fh_data_status'][i]} |")
(ROOT / "docs" / "FH_SCORING_COMPARISON.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
