"""FH Next Wave vs FH score / FH Recommended on the live screener frame. Writes docs/FH_NEXT_WAVE_COMPARISON.md.

Usage: .venv/bin/python scripts/fh_next_wave_compare.py
"""
import sys, warnings
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from app.api import backoffice as api  # noqa: E402
from app.backoffice import fh_recommended  # noqa: E402

df = api._fh_frame()  # same inputs as the live screener: TER, managers, nightly consistency
df = df[(df["plan"] == "Regular") & df["cat"].isin(["large_cap", "mid_cap", "small_cap", "multi_cap", "flexi_cap", "value", "large_mid_cap"])]
rec = df["code"].isin(fh_recommended.FH_RECOMMENDED_MF_CODES)
nw, fh80 = df["nw_pass"], df["fh_score"] >= 80
young = df["history_years"] < 5
L = ["# FH Next Wave vs FH score and FH Recommended", "", "Generated by `backend/scripts/fh_next_wave_compare.py` (Regular plan, equity categories).", "",
     "| Group | Funds | Next Wave | FH score 80+ | Both | FH Recommended | Rec. and Next Wave |", "|---|---|---|---|---|---|---|"]
for name, m in (("All", df.index == df.index), ("History under 5y", young), ("History 5y+", ~young)):
    L.append(f"| {name} | {int(m.sum())} | {int((nw & m).sum())} | {int((fh80 & m).sum())} | {int((nw & fh80 & m).sum())} | {int((rec & m).sum())} | {int((rec & nw & m).sum())} |")
L += ["", "## Next Wave only (not FH score 80+), top 15", "| Fund | Category | Years | Next Wave | FH score | Roll win % |", "|---|---|---|---|---|---|"]
for _, r in df[nw & ~fh80].sort_values("nw_score", ascending=False).head(15).iterrows():
    L.append(f"| {r['name'][:46]} | {r['cat']} | {r['history_years']:.1f} | {r['nw_score']} | {r['fh_score']} | {r['roll_win_pct']} |")
L += ["", "## FH score 80+ but not Next Wave, top 15", "| Fund | Category | Years | Next Wave | FH score | Roll win % |", "|---|---|---|---|---|---|"]
for _, r in df[fh80 & ~nw].sort_values("fh_score", ascending=False).head(15).iterrows():
    L.append(f"| {r['name'][:46]} | {r['cat']} | {r['history_years']:.1f} | {r['nw_score']} | {r['fh_score']} | {r['roll_win_pct']} |")
(ROOT / "docs" / "FH_NEXT_WAVE_COMPARISON.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
