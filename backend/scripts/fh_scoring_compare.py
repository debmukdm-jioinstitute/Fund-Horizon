"""Side-by-side of FH scoring modes (legacy / A / B) on the live screener frame. Writes docs/FH_SCORING_COMPARISON.md.

Usage: .venv/bin/python scripts/fh_scoring_compare.py
Re-runnable baseline: legacy numbers are also saved to data/fh_scoring_baseline_legacy.json (code -> score, signal).
"""
import copy, json, sys, warnings
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
import pandas as pd  # noqa: E402
from app.backoffice import fh_recommended, fh_score, mf_screener  # noqa: E402

base_cfg = fh_score.load_config()
frames = {}
for mode in ("legacy", "A", "B"):
    cfg = copy.deepcopy(base_cfg)
    cfg["ratios"]["mode"] = mode
    df = mf_screener._base_frame().copy()
    # _scored scores with the on-disk config; call the frame builder, then re-score with this mode.
    scored = mf_screener._scored({}, None)
    raw = scored[[c for c in scored.columns if not c.startswith(("fh_", "fhd_", "fhc_"))]].copy()
    frames[mode] = fh_score.score_frame(raw, cfg=cfg, ref=pd.to_datetime(raw["nav_date"], format="%d-%b-%Y", errors="coerce").max())

L, A, B = frames["legacy"], frames["A"], frames["B"]
(ROOT / "data" / "fh_scoring_baseline_legacy.json").write_text(json.dumps(
    {"as_of": str(L["nav_date"].iloc[0]), "scores": {c: [None if pd.isna(s) else float(s), g] for c, s, g in zip(L["code"], L["fh_score"], L["fh_signal"])}}, indent=1))

def dist(f):
    return {"mean_score": round(f["fh_score"].mean(), 1), "median": round(f["fh_score"].median(), 1), "scored": int(f["fh_score"].notna().sum()),
            "mean_coverage": round(f["fh_coverage"].mean(), 3), **{k: int(v) for k, v in f["fh_signal"].value_counts().items()},
            "auto_eligible": int(f["fh_auto"].sum()), "rating_ge4": int((f["fh_rating"] >= 4).sum())}

out = ["# FH scoring: legacy vs category-relative (A, B)", "", "Generated by `backend/scripts/fh_scoring_compare.py` on the shipped NAV dataset.", "",
       "| Metric | legacy | A | B |", "|---|---|---|---|"]
d = {m: dist(f) for m, f in frames.items()}
for k in sorted({k for v in d.values() for k in v}):
    out.append(f"| {k} | " + " | ".join(str(d[m].get(k, 0)) for m in ("legacy", "A", "B")) + " |")
for name, f in (("A", A), ("B", B)):
    delta = (f["fh_score"] - L["fh_score"]).dropna()
    chg = (f["fh_signal"] != L["fh_signal"]).sum()
    out += ["", f"## Mode {name} vs legacy", f"- Funds whose signal changed: {chg} of {len(f)}",
            f"- Score change: mean {delta.mean():+.1f}, median {delta.median():+.1f}, p5 {delta.quantile(.05):+.1f}, p95 {delta.quantile(.95):+.1f}, |change| > 10: {(delta.abs() > 10).sum()}",
            f"- Ratios-filter coverage: legacy {L['fh_ratios_cov'].mean():.2f}, {name} {f['fh_ratios_cov'].mean():.2f}"]
cur = fh_recommended.FH_RECOMMENDED_MF_CODES
out += ["", "## Curated FH list (never auto-removed)", "| Fund | legacy | A | B | data status |", "|---|---|---|---|---|"]
for c in cur:
    i = L.index[L["code"] == c]
    if len(i):
        i = i[0]
        out.append(f"| {L['name'][i][:48]} | {L['fh_score'][i]} {L['fh_signal'][i]} | {A['fh_score'][i]} {A['fh_signal'][i]} | {B['fh_score'][i]} {B['fh_signal'][i]} | {L['fh_data_status'][i]} |")
out += ["", "## Data status counts (legacy frame)", *(f"- {k}: {v}" for k, v in L["fh_data_status"].value_counts().items())]
(ROOT / "docs" / "FH_SCORING_COMPARISON.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
